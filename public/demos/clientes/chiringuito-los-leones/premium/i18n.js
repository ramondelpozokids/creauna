export function getLang() {
  // Prefer localStorage so IT (premium-only) is not overwritten by extras.js currentLang
  const stored = localStorage.getItem('ll_lang');
  if (stored) return stored;
  if (window.LL && typeof window.LL.getLang === 'function') {
    return window.LL.getLang();
  }
  return 'es';
}

export function t(key) {
  const lang = getLang();
  const dict = PREMIUM_I18N[lang] || PREMIUM_I18N.es;
  return dict[key] || PREMIUM_I18N.es[key] || key;
}

export function applyPremiumI18n(root = document) {
  root.querySelectorAll('[data-ll-i18n]').forEach((el) => {
    const key = el.getAttribute('data-ll-i18n');
    const val = t(key);
    if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
      el.placeholder = val;
    } else {
      el.textContent = val;
    }
  });
  root.querySelectorAll('[data-ll-i18n-aria]').forEach((el) => {
    el.setAttribute('aria-label', t(el.getAttribute('data-ll-i18n-aria')));
  });
  root.querySelectorAll('[data-ll-i18n-title]').forEach((el) => {
    el.setAttribute('title', t(el.getAttribute('data-ll-i18n-title')));
  });
}
